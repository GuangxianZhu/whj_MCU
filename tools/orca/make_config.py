"""Make an ORCA hand config.yaml that talks through the KM1M7C bridge.

It copies orca_core's packaged v2 config (orcahand-right / orcahand-left) into
tools/orca/my_hand/ and pins three things, so orca_core does not guess:

    port:       COMx          (the KM1M7C virtual COM port)
    motor_type: dynamixel     (no Feetech probing on our bus)
    baudrate:   57600         (must equal the bridge's SERVO-side baud rate)

and hardware_version (2 = v2.0, 21 = v2.1). U2D2 / KM1M7C are plain adapters
with no ORCA controller board to report it; on a LEFT hand v2.0 and v2.1 drive
the thumb MCP/DIP motors in opposite directions, so it must not be guessed.

Why the baud rate must be pinned: the KM1M7C's USB virtual COM ignores the
baud rate the PC asks for, and the bridge always talks to the servos at its
own fixed rate. Without a pin, orca_core would sweep 1M / 3M / ... and every
rate would "work" (or fail) for the wrong reason.

Usage:
    python make_config.py --list
    python make_config.py ORCA_CORE_DIR --side left --port COM5 [--baud 57600] [--hw 2]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "my_hand")


def list_ports() -> None:
    try:
        import serial.tools.list_ports
    except ImportError:
        print("pyserial not installed; run inside the orca_core environment.")
        return
    ports = list(serial.tools.list_ports.comports())
    if not ports:
        print("  (no serial ports found - is the KM1M7C USB plugged in?)")
    for p in ports:
        vid = f"{p.vid:04X}" if p.vid is not None else "----"
        pid = f"{p.pid:04X}" if p.pid is not None else "----"
        print(f"  {p.device:8s}  VID:PID {vid}:{pid}  {p.description}")


def make(orca_dir: str, side: str, port: str, baud: int, hw: int = 2) -> str:
    src = os.path.join(orca_dir, "orca_core", "models", "v2", f"orcahand-{side}", "config.yaml")
    if not os.path.isfile(src):
        sys.exit(f"cannot find {src}")
    os.makedirs(OUT_DIR, exist_ok=True)
    dst = os.path.join(OUT_DIR, "config.yaml")

    # Re-running keeps calibration.yaml / local_config.yaml (they sit beside it)
    # and only rewrites config.yaml from the packaged one.
    text = open(src, encoding="utf-8").read()
    text = re.sub(r"(?m)^(port|motor_type|baudrate|hardware_version):.*\n", "", text)
    header = (
        "# Generated by whj_MCU tools/orca/make_config.py - talks through the KM1M7C bridge.\n"
        f"# Copied from orca_core models/v2/orcahand-{side}/config.yaml.\n"
        f"port: {port}\n"
        "motor_type: dynamixel\n"
        f"baudrate: {baud}   # = bridge servo-side baud; the USB COM itself ignores it\n"
        f"hardware_version: {hw}   # 2 = v2.0, 21 = v2.1 (no ORCA board to ask on a plain adapter)\n"
    )
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + text)
    return dst


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("orca_dir", nargs="?")
    ap.add_argument("--list", action="store_true", help="list serial ports and exit")
    ap.add_argument("--side", choices=["right", "left"], default="right")
    ap.add_argument("--port")
    ap.add_argument("--baud", type=int, default=57600)
    ap.add_argument("--hw", type=int, choices=[2, 21], default=2,
                    help="hand hardware version: 2 = v2.0 (default), 21 = v2.1")
    a = ap.parse_args()
    if a.list:
        list_ports()
        return 0
    if not a.orca_dir or not a.port:
        ap.error("orca_dir and --port are required")
    print("written:", make(a.orca_dir, a.side, a.port.strip().upper(), a.baud, a.hw))
    return 0


if __name__ == "__main__":
    sys.exit(main())
