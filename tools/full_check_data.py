def render_md(out):
    L = ['# XL330 通信全面检查', '',
         '所有接线都已完成，但通信有问题时，从头逐项测一遍。每一项都写了测哪里、应该是多少，以及不对时最可能的原因。'
         ' 交互版（填数自动判断）见 [`通信全面检查.html`](通信全面检查.html)，下载后用浏览器打开。', '',
         '## 记号', '',
         '- **6下**：第 6 列槽下方（A–F 行）的任意一个孔或针；**6上**：第 6 列槽上方（G–L 行）。',
         '- **V1 +、V1 −**：电源轨，外部 5V 和 GND。所有 GND 都接 V1 −，V3 不用。',
         '- **模式 A/B/C**：为了测试临时改的固件状态。A：DIR = 0，UART 空闲；B：DIR = 1，TX 引脚当 GPIO 输出 1；C：DIR = 1，TX 输出 0。',
         '- 按顺序测，遇到第一个不对的项先修好，再往下测。后面的项默认前面都已通过。', '']
    for s in S:
        L += [f'## {s["id"]}. {s["t"]}', '', s['setup'].replace('<b>', '**').replace('</b>', '**'), '',
              '| # | 测量 | 应该 | 不对时 |', '|---|---|---|---|']
        for it in s['items']:
            L.append(f'| {it["id"]} | {it["p"]} | {it["e"]} | {it["cause"]} |')
        L.append('')
    L += ['## 正常的 ping 应答', '',
          '`FF FF FD 00 01 07 00 55 00 B0 04 xx CRC_L CRC_H`，一共 14 字节。',
          '`55` 表示这是应答包，`00` 表示没有错误，`B0 04` 是型号 1200（XL330-M288；M077 是 `A6 04`），`xx` 是固件版本，所以最后两个 CRC 字节因舵机而异。', '',
          '## 按现象找方向', '',
          '| 现象 | 先看 |',
          '|---|---|',
          '| DATA 上从来没有波形，6.7 的 LED 也不亮 | 第 4 节（发送通路）、6.1、6.2 |',
          '| LED 能亮，但 ping 没有应答 | 第 5 节（接收通路）、6.2、6.4、6.5 |',
          '| 收到的是自己刚发的 10 个字节 | 4.9：1OE 没被拉高，S7 断开 |',
          '| 偶尔有应答，经常 CRC 错误 | 6.4（TXE 和 TC）、2.1（地没连通）、1.6、1.7（电阻阻值） |',
          '| 舵机一转就断 | 外部电源电流不够，C4 没接好 |', '']
    open(out, 'w', encoding='utf-8').write('\n'.join(L))

if __name__ == '__main__':
    if sys.argv[1] == 'json': print(json.dumps(S, ensure_ascii=False))
    else: render_md(sys.argv[2])
